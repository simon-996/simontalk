"""Check the shipped Web font against the complete, licensed source font."""

import argparse
import hashlib
import json
from pathlib import Path

from fontTools.ttLib import TTFont


ROOT = Path(__file__).resolve().parents[1]
FONT_DIR = ROOT / "apps/client/assets/fonts"
METADATA = ROOT / "apps/client/lib/core/web_font_metadata.dart"


def metadata_text():
    data = (FONT_DIR / "NotoSansSC.woff2").read_bytes()
    digest = hashlib.sha256(data).hexdigest()
    return (
        "// Generated by scripts/prepare_web_fonts.py; do not edit.\n"
        f"const webFontLength = {len(data)};\n"
        "const webFontSha256 =\n"
        f"    '{digest}';\n"
    )


def check_fonts():
    source_path = FONT_DIR / "NotoSansSC.ttf"
    web_path = FONT_DIR / "NotoSansSC.woff2"
    if not web_path.is_file():
        raise ValueError("Missing Web font; run scripts/prepare_web_fonts.py")
    if web_path.stat().st_size >= 8 * 1024 * 1024:
        raise ValueError("Web Chinese font must be smaller than 8 MiB")
    if not METADATA.is_file() or METADATA.read_text() != metadata_text():
        raise ValueError("Web font length/digest metadata is missing or stale")
    with TTFont(source_path) as source, TTFont(web_path) as web:
        if web.flavor != "woff2":
            raise ValueError("Web font must use WOFF2")
        if source.getBestCmap() != web.getBestCmap():
            raise ValueError("Unicode coverage changed")
        if source.getGlyphOrder() != web.getGlyphOrder():
            raise ValueError("Glyph ordering changed")
        if set(source.reader.keys()) != set(web.reader.keys()):
            raise ValueError("Font tables changed")
        # These tables encode Unicode maps, metrics, variable weights, layout,
        # instructions and license/name records. WOFF2 transforms only glyf/loca.
        for tag in source.reader.keys():
            if tag not in {"glyf", "loca", "head"}:
                if source.reader[tag] != web.reader[tag]:
                    raise ValueError(f"Font table changed: {tag}")
        for field in ("unitsPerEm", "xMin", "yMin", "xMax", "yMax"):
            if getattr(source["head"], field) != getattr(web["head"], field):
                raise ValueError(f"Font bounds changed: {field}")
        for name in source.getGlyphOrder():
            original = source["glyf"][name].getCoordinates(source["glyf"])
            decoded = web["glyf"][name].getCoordinates(web["glyf"])
            if original[:2] != decoded[:2]:
                raise ValueError(f"Glyph outline changed: {name}")
            if [flag & 1 for flag in original[2]] != [flag & 1 for flag in decoded[2]]:
                raise ValueError(f"Glyph curve points changed: {name}")
        print(f"Full Unicode mappings preserved: {len(source.getBestCmap())}")
    print(f"Chinese font: {source_path.stat().st_size:,} -> {web_path.stat().st_size:,} bytes")


def check_bundle(build_dir):
    assets = build_dir / "assets"
    if (assets / "assets/fonts/NotoSansSC.ttf").exists():
        raise ValueError("Uncompressed Chinese font is still in the Web bundle")
    original = FONT_DIR / "NotoSansSC.woff2"
    shipped = assets / "assets/fonts/NotoSansSC.woff2"
    if hashlib.sha256(original.read_bytes()).digest() != hashlib.sha256(shipped.read_bytes()).digest():
        raise ValueError("Shipped Web font does not match the verified font")
    manifest = json.loads((assets / "FontManifest.json").read_text())
    families = {entry["family"] for entry in manifest}
    if "Roboto" not in families or "NotoSansSC" in families:
        raise ValueError("Expected local Roboto and explicit Web Chinese loading")
    print("Web bundle contains the verified compressed font and local Roboto")


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--web-build", type=Path)
    args = parser.parse_args()
    check_fonts()
    if args.web_build:
        check_bundle(args.web_build)
